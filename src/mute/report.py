
"""Self-contained HTML report for a mute audit."""

from datetime import datetime
from html import escape
from pathlib import Path


VERDICT_COLORS = {
    "broken":   ("#fee2e2", "#991b1b"),
    "ancient":  ("#ffedd5", "#9a3412"),
    "aging":    ("#fef3c7", "#92400e"),
    "healthy":  ("#dcfce7", "#15803d"),
}


def _badge(verdict):
    bg, fg = VERDICT_COLORS.get(verdict, ("#f3f4f6", "#4b5563"))
    return (
        '<span style="display:inline-block;padding:2px 10px;border-radius:10px;'
        'font-weight:600;font-size:11px;background:' + bg + ';color:' + fg
        + ';text-transform:uppercase;letter-spacing:0.5px;">'
        + escape(verdict) + '</span>'
    )


def _card(s):
    issues = ", ".join(s.issue_refs) if s.issue_refs else "&mdash;"
    reason = s.reason if s.reason else "(no reason)"
    added = (s.added_date + " by " + s.added_by) if s.added_by else "&mdash;"
    age = (str(s.age_days) + " days") if s.age_days > 0 else "&mdash;"

    return (
        '<div style="background:white;border:1px solid #e5e7eb;border-radius:8px;'
        'padding:14px 18px;margin:10px 0;">'
        '<div style="display:flex;justify-content:space-between;align-items:center;'
        'flex-wrap:wrap;gap:8px;margin-bottom:8px;">'
        '<div style="font-family:ui-monospace,Menlo,monospace;font-size:13px;">'
        + escape(s.file) + '::' + escape(s.test_name) + '</div>'
        '<div>' + _badge(s.verdict) + ' &nbsp; '
        '<span style="font-size:12px;color:#666;">' + escape(s.kind) + '</span></div>'
        '</div>'
        '<div style="font-size:13px;color:#444;line-height:1.6;">'
        '<div><strong>reason:</strong> ' + escape(reason) + '</div>'
        '<div><strong>issues:</strong> ' + escape(issues) + '</div>'
        '<div><strong>added:</strong> ' + escape(added) + '</div>'
        '<div><strong>age:</strong> ' + escape(age) + '</div>'
        '</div></div>'
    )


def _stat_card(label, value, color="#111827"):
    return (
        '<div style="background:white;border:1px solid #e5e7eb;border-radius:8px;'
        'padding:16px 20px;flex:1;min-width:130px;">'
        '<div style="font-size:11px;color:#666;text-transform:uppercase;'
        'letter-spacing:0.5px;font-weight:600;">' + escape(label) + '</div>'
        '<div style="font-size:26px;font-weight:700;color:' + color
        + ';margin-top:6px;">' + str(value) + '</div>'
        '</div>'
    )


def render_report(report, output_path=None):
    generated = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    stats_html = "".join([
        _stat_card("total", report.total),
        _stat_card("broken", report.broken,
                   "#b91c1c" if report.broken else "#15803d"),
        _stat_card("ancient", report.ancient,
                   "#b45309" if report.ancient else "#15803d"),
        _stat_card("aging", report.aging,
                   "#b45309" if report.aging else "#15803d"),
        _stat_card("healthy", report.healthy, "#15803d"),
        _stat_card("no reason", report.without_reason,
                   "#b91c1c" if report.without_reason else "#15803d"),
        _stat_card("no issue", report.without_issue,
                   "#b91c1c" if report.without_issue else "#15803d"),
    ])

    sections = []
    for verdict in ("broken", "ancient", "aging", "healthy"):
        items = [s for s in report.suppressions if s.verdict == verdict]
        if not items:
            continue
        cards = "".join(_card(s) for s in items)
        sections.append(
            '<h2 style="font-size:16px;margin:28px 0 10px 0;color:#374151;'
            'border-bottom:1px solid #e5e7eb;padding-bottom:6px;">'
            + verdict.upper() + ' (' + str(len(items)) + ')</h2>' + cards
        )

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>mute audit report</title>
</head>
<body style="font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif;
             margin:0;padding:32px;background:#f9fafb;color:#111827;line-height:1.5;">
<h1 style="margin:0 0 4px 0;font-size:24px;">mute audit report</h1>
<div style="color:#666;font-size:14px;margin-bottom:24px;">
  Generated: <strong>{escape(generated)}</strong>
</div>
<div style="display:flex;gap:12px;flex-wrap:wrap;">
  {stats_html}
</div>
{''.join(sections)}
<footer style="margin-top:48px;padding-top:16px;border-top:1px solid #e5e7eb;
               color:#9ca3af;font-size:12px;text-align:center;">
  Generated by mute &middot; {escape(generated)}
</footer>
</body>
</html>
"""

    if output_path is None:
        Path("reports").mkdir(exist_ok=True)
        ts = datetime.now().strftime("%Y%m%d-%H%M%S")
        output_path = "reports/mute-" + ts + ".html"

    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")
    return str(out)
